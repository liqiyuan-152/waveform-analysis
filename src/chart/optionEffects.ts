export function changedOptionKeys(
  before: ResolvedWaveformChartProps,
  after: ResolvedWaveformChartProps,
) {
  return (Object.keys(optionEffects) as Array<keyof WaveformChartProps>).filter(
    (key) => before[key] !== after[key],
  )
}

